import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";

test("email and fulfillment migration queues idempotent emails and thresholded stock alerts", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
      create function auth.jwt() returns jsonb language sql stable
        as $$ select '{"role":"service_role"}'::jsonb $$;
      create schema vault;
      create schema net;
      create table vault.decrypted_secrets (
        name text,
        decrypted_secret text,
        created_at timestamptz default now()
      );
      create function net.http_post(
        url text,
        headers jsonb,
        body jsonb,
        timeout_milliseconds integer
      ) returns bigint language sql as $$ select 1::bigint $$;
      create table public.orders (
        id uuid primary key default gen_random_uuid(),
        user_id uuid,
        payment_status text,
        status text,
        total numeric not null default 0,
        payment_method text not null default 'paystack' check (payment_method = 'paystack'),
        paystack_ref text,
        delivery_fee numeric not null default 0,
        promo_code_id integer,
        shipping_name text,
        shipping_email text,
        shipping_phone text,
        shipping_address text,
        shipping_city text,
        shipping_state text,
        whatsapp_number text,
        order_note text,
        tracking_number text,
        tracking_url text
      );
      create table public.promo_codes (
        id integer generated by default as identity primary key,
        uses integer not null default 0,
        active boolean not null default true,
        expires_at timestamptz,
        max_uses integer,
        min_order numeric not null default 0,
        type text not null default 'fixed',
        value numeric not null default 0
      );
      create table public.products (
        id uuid primary key default gen_random_uuid(),
        name text,
        price numeric,
        stock integer
      );
      create table public.product_variants (
        id uuid primary key default gen_random_uuid(),
        product_id uuid references public.products(id),
        name text,
        type text,
        price numeric,
        stock integer
      );
      create table public.delivery_zones (
        id integer generated by default as identity primary key,
        zone_name text not null,
        states text[] not null,
        fee numeric not null
      );
      create table public.order_items (
        id uuid primary key default gen_random_uuid(),
        order_id uuid references public.orders(id),
        product_id uuid references public.products(id),
        variant_id uuid references public.product_variants(id),
        quantity integer,
        unit_price numeric
      );
      create function public.decrement_stock(p_product_id uuid, p_quantity integer)
        returns void language plpgsql as $$
        begin
          update public.products set stock = stock - p_quantity
          where id = p_product_id and stock >= p_quantity;
          if not found then raise exception 'Insufficient product stock'; end if;
        end;
        $$;
      create function public.decrement_variant_stock(p_variant_id uuid, p_quantity integer)
        returns void language plpgsql as $$
        begin
          update public.product_variants set stock = stock - p_quantity
          where id = p_variant_id and stock >= p_quantity;
          if not found then raise exception 'Insufficient variant stock'; end if;
        end;
        $$;
      alter table public.orders enable row level security;
      create policy "admin read all orders" on public.orders
        for select using (true);
    `);

    const checkoutMigration = await readFile(
      new URL("../supabase/migrations/20260929064943_switch_payment_provider_to_korapay.sql", import.meta.url),
      "utf8"
    );
    await db.exec(checkoutMigration);
    assert.equal((await db.query(
      "select column_default from information_schema.columns where table_schema='public' and table_name='orders' and column_name='payment_method'"
    )).rows[0].column_default, "'korapay'::text");
    assert.equal((await db.query(
      "select count(*)::integer as count from pg_policies where schemaname='public' and tablename='orders'"
    )).rows[0].count, 1);
    assert.equal((await db.query(
      "select prosecdef and 'search_path=\"\"' = any(proconfig) as hardened from pg_proc where oid='public.finalize_order(jsonb)'::regprocedure"
    )).rows[0].hardened, true);
    assert.equal((await db.query(
      "select has_function_privilege('anon', 'public.finalize_order(jsonb)', 'execute') as allowed"
    )).rows[0].allowed, false);
    assert.equal((await db.query(
      "select has_function_privilege('authenticated', 'public.finalize_order(jsonb)', 'execute') as allowed"
    )).rows[0].allowed, false);
    assert.equal((await db.query(
      "select has_function_privilege('service_role', 'public.finalize_order(jsonb)', 'execute') as allowed"
    )).rows[0].allowed, true);

    const migration = await readFile(
      new URL("../supabase/migrations/20261013100534_email_tracking_low_stock_automation.sql", import.meta.url),
      "utf8"
    );
    await db.exec(migration);
    await db.exec(migration);
    assert.equal((await db.query(
      "select count(*)::integer as count from pg_policies where schemaname='public' and tablename='orders'"
    )).rows[0].count, 0);

    const { rows: productsForCheckout } = await db.query(
      "insert into public.products (name, price, stock) values ('Checkout serum', 10, 10) returning id"
    );
    await db.query(
      "insert into public.delivery_zones (zone_name, states, fee) values ('Lagos', array['Lagos'], 3)"
    );
    const checkoutPayload = {
      user_id: "11111111-1111-4111-8111-111111111111",
      payment_reference: "KORA-VERIFIED-1",
      verified_amount: 23,
      shipping: { state: "Lagos", name: "Customer", email: "customer@example.com" },
      items: [{
        product_id: productsForCheckout[0].id,
        quantity: 2,
        unit_price: 1,
      }],
    };
    await assert.rejects(
      db.query("select public.finalize_order($1::jsonb)", [{
        ...checkoutPayload,
        payment_reference: "KORA-UNDERPAID",
        verified_amount: 1,
      }]),
      /Verified payment amount does not match/
    );
    const { rows: finalizedOrders } = await db.query(
      "select public.finalize_order($1::jsonb) as order",
      [checkoutPayload]
    );
    assert.equal(finalizedOrders[0].order.payment_status, "paid");
    assert.equal(Number(finalizedOrders[0].order.total), 23);
    assert.equal((await db.query(
      "select stock from public.products where id = $1",
      [productsForCheckout[0].id]
    )).rows[0].stock, 8);
    assert.equal((await db.query(
      "select unit_price from public.order_items where order_id = $1",
      [finalizedOrders[0].order.id]
    )).rows[0].unit_price, "10");

    const { rows: insertedOrders } = await db.query(`
      insert into public.orders (payment_status, status, shipping_name, shipping_email)
      values ('paid', 'confirmed', 'Customer', 'customer@example.com')
      returning id
    `);
    const orderId = insertedOrders[0].id;
    let { rows } = await db.query(
      "select event_key, recipient from public.email_outbox where order_id = $1",
      [orderId]
    );
    assert.deepEqual(rows, [{ event_key: "order-paid", recipient: "customer@example.com" }]);

    await db.query(
      `update public.orders set tracking_number = 'TRACK-1',
        tracking_url = 'https://carrier.example/track/1', status = 'shipped'
       where id = $1`,
      [orderId]
    );
    await db.query("update public.orders set status = 'shipped' where id = $1", [orderId]);
    ({ rows } = await db.query(
      "select event_key, payload from public.email_outbox where order_id = $1 order by event_key",
      [orderId]
    ));
    assert.equal(rows.length, 2);
    assert.equal(rows[1].event_key, "status-shipped");
    assert.equal(rows[1].payload.tracking_url, "https://carrier.example/track/1");
    assert.equal(await db.query(
      "select relrowsecurity from pg_class where oid = 'public.email_outbox'::regclass"
    ).then((result) => result.rows[0].relrowsecurity), true);
    assert.equal((await db.query(
      "select has_table_privilege('anon', 'public.email_outbox', 'select') as allowed"
    )).rows[0].allowed, false);
    await assert.rejects(
      db.query("update public.orders set tracking_url = 'javascript:alert(1)' where id = $1", [orderId]),
      /orders_tracking_url_https/
    );

    const { rows: insertedProducts } = await db.query(
      "insert into public.products (name, stock) values ('Serum', 5) returning id"
    );
    const productId = insertedProducts[0].id;
    await db.query("update public.products set stock = 4 where id = $1", [productId]);
    assert.equal((await db.query(
      "select count(*)::integer as count from public.email_outbox where event_key = 'low-stock'"
    )).rows[0].count, 1);

    await db.query("update public.products set stock = 6 where id = $1", [productId]);
    await db.query("update public.products set stock = 5 where id = $1", [productId]);
    assert.equal((await db.query(
      "select count(*)::integer as count from public.email_outbox where event_key = 'low-stock'"
    )).rows[0].count, 2);

    const { rows: variantProducts } = await db.query(
      "insert into public.products (name, stock) values ('Shade range', 20) returning id"
    );
    const variantProductId = variantProducts[0].id;
    const { rows: variants } = await db.query(
      `insert into public.product_variants (product_id, name, type, stock)
       values ($1, 'Warm beige', 'shade', 5) returning id`,
      [variantProductId]
    );
    await db.query("update public.products set stock = 4 where id = $1", [variantProductId]);
    assert.equal((await db.query(
      "select count(*)::integer as count from public.email_outbox where event_key = 'low-stock'"
    )).rows[0].count, 3);

    await db.query("update public.product_variants set stock = 6 where id = $1", [variants[0].id]);
    await db.query("update public.product_variants set stock = 5 where id = $1", [variants[0].id]);
    assert.equal((await db.query(
      "select count(*)::integer as count from public.email_outbox where event_key = 'low-stock'"
    )).rows[0].count, 4);
  } finally {
    await db.close();
  }
});
